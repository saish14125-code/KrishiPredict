st.markdown("""
### Data handling rules applied
- 2026 daily rainfall is **never** merged with 1997-2022 crop records; subdivisions are **not** treated as districts.
- Rainfall is **not** a model feature. The only rainfall-crop view is a state-level exploratory correlation for states matching one subdivision.
- Yield outliers and zero-production records are flagged, not deleted; they are excluded only from yield statistics and ML.
- Coconut (nuts) and Cotton/Jute/Mesta (bales) are not recorded in tonnes and are excluded from tonnage totals and the ML model.

### Technologies
Python, Pandas, NumPy, Scikit-learn (pipelines, target encoding), XGBoost (optional), Plotly, Streamlit, Joblib.

### Machine learning
Linear Regression, Random Forest and XGBoost predict log(1+yield) from state, district, crop, season, year and area. Two historical-median baselines
are reported. Selection by validation RMSE (2018-19); final evaluation on 2020-22.

### Architecture
`data/` -> `src/preprocessing.py` -> `processed/` -> `src/model_training.py` -> `models/` ; Streamlit `app.py` + `pages/` read processed data and the saved model through cached loaders.

### Limitations
- Units are assumed (tonnes, hectares); the files carry no unit labels.
- The number of reporting districts nearly doubles between 1997 and 2022, so raw yearly totals are partly a coverage effect.
- No weather input; predictions cannot capture drought, floods, or management.
- Models cannot extrapolate to future years; no district boundaries are bundled, so no maps.
- Names of districts changed over time; some districts have short histories.

### Future scope
District-level historical rainfall (IMD gridded data) aligned with crop years, satellite indices (NDVI), district boundary maps, per-crop models, prediction intervals via quantile models.
""")

